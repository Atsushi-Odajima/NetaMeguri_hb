import { createApp } from '../server/src/app.js';
import { seedSample } from '../server/src/seed/sample.js';
import { listContent, runChecks, getPack } from '../server/src/domain/content.js';
import { askStrategist, search } from '../server/src/domain/search.js';
import { recyclingCandidates, feedback } from '../server/src/domain/performance.js';
import { campaignGuard } from '../server/src/domain/campaigns.js';
import { ideaMemory } from '../server/src/domain/ideas.js';

const app = createApp();
const t0 = Date.now();
const s = await seedSample(app);
console.log('seeded in', Date.now() - t0, 'ms', s.ids);
const pack = getPack(s.ctx, s.ids.pack);
console.log('pack byKind', pack.byKind);
for (const it of pack.items.slice(0, 4)) console.log('---', it.platform, it.format, '\n' + it.body.slice(0, 400));
const car = pack.items.find((i) => i.format === 'carousel');
console.log('carousel', JSON.stringify(car?.structured, null, 1).slice(0, 600));
const sv = pack.items.find((i) => i.format === 'short_video');
console.log('short', JSON.stringify(sv?.structured).slice(0, 400));
const blog = pack.items.find((i) => i.format === 'article');
console.log('blog\n', blog?.body.slice(0, 800));
const th = pack.items.find((i) => i.platform === 'threads')!;
console.log('checks', JSON.stringify(await runChecks(s.ctx, th.id), null, 1).slice(0, 1500));
const mem = ideaMemory(s.ctx);
console.log('memory', Object.fromEntries(Object.entries(mem).map(([k, v]) => [k, v.length])));
console.log('search', search(s.ctx, 'まだThreadsで使ってないAI開発ネタ').hits.slice(0, 3).map((h) => h.title + ' / ' + h.matchedBy));
console.log('search2', search(s.ctx, '過去に反応が良かった失敗談').hits.slice(0, 3).map((h) => h.title + ' / ' + h.matchedBy));
console.log('search3', search(s.ctx, 'ProofFlow関連の未使用Idea').hits.slice(0, 3).map((h) => h.title + ' / ' + h.matchedBy));
const a = await askStrategist(s.ctx, '今日Threadsに何か投稿したい');
console.log('strategist', a.answer);
console.log('recycling', recyclingCandidates(s.ctx).map((r) => r.reason));
console.log('feedback', feedback(s.ctx, 'topic').insight);
console.log('guard', campaignGuard(s.ctx, s.ids.campaign).warnings.map((w) => w.message));
console.log('content count', listContent(s.ctx, { limit: 1000 }).length);
